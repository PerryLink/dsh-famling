/**
 * MB-107 (E3): JSDoc/lint/checkJs tooling gate.
 *
 * Proves the minimal chain added by MB-107 is wired and remains honest:
 *   - package.json exposes check:content / lint / typecheck and release:check
 *     runs the new gates;
 *   - scripts/check-jsdoc.mjs passes on the real package and its detectors
 *     actually reject undocumented exports / hand-edited generated blocks /
 *     debugger statements (negative fixtures);
 *   - scripts/typecheck.mjs really runs checkJs when a compiler is resolvable,
 *     and prints an explicit skip otherwise (never a silent pass);
 *   - scripts/tsconfig.checkjs.json and the MB-107 doc ship with the package.
 */
import assert from 'node:assert/strict'
import { existsSync, readFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { test } from 'node:test'

import {
  JSDOC_DEBT_FILES,
  JSDOC_FILES,
  PLUGIN_ROOT,
  checkPackage,
  inspectGeneratedBlocks,
  inspectJsDoc,
  inspectRuntimeLint,
} from '../scripts/check-jsdoc.mjs'
import { resolveTypeScript } from '../scripts/typecheck.mjs'

const TOP = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(TOP, 'package.json'), 'utf8'))
const clientSource = readFileSync(join(TOP, 'client.js'), 'utf8')
const chunkSources = ['human', 'cat', 'dog'].map((kind) => readFileSync(join(TOP, 'client.anims.' + kind + '.js'), 'utf8'))

test('package.json wires the MB-107 gates into check and release:check', () => {
  assert.equal(pkg.scripts['gen:content'], 'node scripts/gen-content-constants.mjs')
  assert.equal(pkg.scripts['check:content'], 'node scripts/gen-content-constants.mjs --check')
  assert.equal(pkg.scripts.lint, 'node scripts/check-jsdoc.mjs')
  assert.equal(pkg.scripts.typecheck, 'node scripts/typecheck.mjs')
  assert.ok(pkg.scripts.check.includes('scripts/gen-content-constants.mjs --check'), 'npm run check also gates the generated content blocks')
  for (const gate of ['npm run lint', 'npm run typecheck']) assert.ok(pkg.scripts['release:check'].includes(gate), 'release:check runs ' + gate)
  assert.match(pkg.version, /^\d+\.\d+\.\d+$/, 'MB-107 keeps the existing semver version (no bump required)')
})

test('the JSDoc/lint gate is green on the real package and lists its enforced scope', () => {
  const result = checkPackage()
  assert.deepEqual(result.problems, [], 'check-jsdoc must stay green: ' + result.problems.join(' / '))
  assert.ok(result.stats.syntaxFiles >= 20, 'node --check covers the package sources (' + result.stats.syntaxFiles + ')')
  assert.ok(result.stats.checkedExports >= 40, 'exported declarations are actually inspected (' + result.stats.checkedExports + ')')
  assert.equal(result.stats.jsdocFiles, JSDOC_FILES.length)
  assert.equal(result.stats.generatedChunks, 3)
  for (const file of JSDOC_FILES) assert.ok(existsSync(join(TOP, file)), 'enforced file exists: ' + file)
  for (const file of JSDOC_DEBT_FILES) assert.ok(existsSync(join(TOP, file)), 'documented debt file still exists: ' + file)
})

test('undocumented exports are rejected (negative fixtures)', () => {
  const noDoc = inspectJsDoc('export function helper(alpha, beta) {\n  return alpha + beta\n}\n', 'fixture.js')
  assert.ok(noDoc.some((problem) => /missing a preceding JSDoc/.test(problem)), 'missing block detected: ' + JSON.stringify(noDoc))
  const partial = inspectJsDoc('/** Does a thing. */\nexport function helper(alpha) {\n  return alpha\n}\n', 'fixture.js')
  assert.ok(partial.some((problem) => /missing @param alpha/.test(problem)), 'missing @param detected: ' + JSON.stringify(partial))
  assert.ok(partial.some((problem) => /missing @returns/.test(problem)), 'missing @returns detected: ' + JSON.stringify(partial))
  const complete = inspectJsDoc('/**\n * Does a thing.\n * @param {number} alpha Input.\n * @returns {number} Output.\n */\nexport function helper(alpha) {\n  return alpha\n}\n/** A documented constant. */\nexport const VALUE = 1\n', 'fixture.js')
  assert.deepEqual(complete, [], 'complete JSDoc passes')
  const undocumentedConst = inspectJsDoc('export const VALUE = 1\n', 'fixture.js')
  assert.ok(undocumentedConst.some((problem) => /exported VALUE is missing/.test(problem)), 'undocumented const detected')
})

test('generated blocks and runtime lint reject hand edits (negative fixtures)', () => {
  assert.deepEqual(inspectGeneratedBlocks(clientSource, chunkSources), [], 'the committed generated blocks satisfy the banner contract')
  const withoutBanner = clientSource.replace('@generated by scripts/gen-content-constants.mjs - do not edit this block by hand.', '')
  assert.ok(inspectGeneratedBlocks(withoutBanner, chunkSources).some((problem) => /missing its @generated banner/.test(problem)), 'removed banner detected')
  const duplicatedMarker = clientSource.replace('// <dsh-famling:event-clips:begin>', '// <dsh-famling:event-clips:begin>\n    // <dsh-famling:event-clips:begin>')
  assert.ok(inspectGeneratedBlocks(duplicatedMarker, chunkSources).some((problem) => /exactly one/.test(problem)), 'duplicated marker detected')
  assert.deepEqual(inspectRuntimeLint('const value = 1\n', 'ok.js'), [])
  assert.equal(inspectRuntimeLint('function f() { debugger }\n', 'bad.js').length, 1, 'debugger statement detected')
})

test('typecheck either really runs checkJs or skips honestly', () => {
  const resolved = resolveTypeScript()
  const result = spawnSync(process.execPath, [join(TOP, 'scripts', 'typecheck.mjs')], { cwd: TOP, encoding: 'utf8' })
  assert.equal(result.status, 0, 'typecheck must exit 0 (real pass or honest skip): ' + (result.stderr || result.stdout))
  const output = result.stdout + result.stderr
  if (resolved && resolved.typeRoots) assert.ok(output.includes('checkJs ok'), 'compiler available -> real checkJs: ' + output.trim())
  else assert.ok(output.includes('skipped'), 'compiler unavailable -> explicit skip: ' + output.trim())
})

test('checkJs config and the MB-107 doc ship with the package', () => {
  const configPath = join(TOP, 'scripts', 'tsconfig.checkjs.json')
  assert.ok(existsSync(configPath), 'scripts/tsconfig.checkjs.json exists')
  const config = readFileSync(configPath, 'utf8')
  for (const option of ['"allowJs": true', '"checkJs": true', '"noEmit": true', '"target": "ES2022"']) assert.ok(config.includes(option), 'config sets ' + option)
  const doc = readFileSync(join(TOP, 'docs', 'CONTENT-CONSTANTS-2026-11-20.md'), 'utf8')
  for (const needle of ['check-jsdoc.mjs', 'typecheck.mjs', 'tsconfig.checkjs.json', 'source-sha256']) assert.ok(doc.includes(needle), 'doc documents ' + needle)
  assert.ok(doc.includes('MB-108'), 'doc records the content-extension checkJs follow-up')
})

test('the MB-107 doc is packed with the package docs directory', () => {
  const files = pkg.files || []
  assert.ok(files.includes('docs'), 'package.json publishes the docs directory (which includes the MB-107 doc)')
})
